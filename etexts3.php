<h3>Critical Source Materials for Buddhist Textual Studies</h3>
The Resource for Kanjur and Tanjur Studies (rKTs) presents an extended repository of
machine-generated e-texts. These digital renditions have been created using BDRC’s OCR
(Optical Character Recognition) application for Tibetan, released in March 2025.

<h3>Technical Implementation and Background</h3>
The repository employs a systematic approach to the organization and retrieval of textual
data:
<br>• Direct OCR processing of source materials without subsequent human editorial
intervention
<br>• Structural organization following canonical divisions and traditional text hierarchies
<br>• Unicode compliance ensuring proper display of Tibetan script across platforms and
applications
<br>• Downloadable formats permitting offline scholarly analysis and integration with
research workflows
<br><br>
These e-texts were generated using models developed by Eric Werner in collaboration with
Élie Roux, Pentsok W Rtsang, and the Monlam AI team.

<h3>Quality Statement</h3>
The present corpus constitutes raw OCR output without manual correction or editorial
review. As such, researchers should note:
<br>• Character recognition accuracy varies according to script type, image quality, and
textual layout
<br>• The OCR models employed are in continued development
<br>• Results may exhibit inconsistencies in complex passages or where source materials
present degradation
<br>• Occasional character substitutions, omissions, or misrecognitions may be present
<br>Users are advised to verify critical passages against original sources when employing these
materials for substantive philological or doctrinal analysis.

<h3>Community Collaboration</h3>

The rKTs team welcomes scholarly contributions in the form of corrected or edited versions
of these texts. All contributions will be properly attributed to their original authors.
<br>If you find errors in these e-texts or if you have good-quality e-texts to contribute, please
contact us.

